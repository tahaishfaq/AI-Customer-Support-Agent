const VARIANTS = [
  { suffix: "", actor: null },
  { suffix: " (studio)", actor: "owner" },
  { suffix: " (embed)", actor: "embed" },
  { suffix: " (retry)", actor: "system" },
  { suffix: " (concurrent)", actor: "system" },
];

/** @returns {Array<{id:string,domain:string,baseTitle:string,scenario:string,actor:string,expected:string,variant:string}>} */
export function buildRegistryRows() {
  const rows = [];
  let id = 1;
  for (const domain of DOMAINS) {
    for (const [title, actor, expected] of domain.cases) {
      for (const v of VARIANTS) {
        if (id > 1000) break;
        rows.push({
          id: `E${String(id).padStart(4, "0")}`,
          domain: domain.id,
          baseTitle: title,
          scenario: `${title}${v.suffix}`,
          actor: v.actor || actor,
          expected,
          variant: v.suffix.replace(/^\s*\(|\)$/g, "") || "base",
        });
        id++;
      }
      if (id > 1000) break;
    }
    if (id > 1000) break;
  }
  while (id <= 1000) {
    rows.push({
      id: `E${String(id).padStart(4, "0")}`,
      domain: "D10",
      baseTitle: `Regression slot ${id}`,
      scenario: `Regression slot ${id}`,
      actor: "system",
      expected: "Covered by automated smoke + owner manual test",
      variant: "base",
    });
    id++;
  }
  return rows;
}

